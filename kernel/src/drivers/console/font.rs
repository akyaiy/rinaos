pub struct Font {
    pub width: usize,
    pub height: usize,
}

pub const DEFAULT_FONT: Font = Font {
    width: 8,
    height: 16,
};

impl Font {
    pub fn row_bits(&self, ch: u8, row: usize) -> u8 {
        if row >= self.height {
            return 0;
        }

        let glyph_row = row / 2;

        if glyph_row >= 7 {
            return 0;
        }

        glyph_5x7(ch)[glyph_row] << 1
    }
}

